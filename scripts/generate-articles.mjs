function buildStoryOutline(topic, articleNumber) {
  const topicData = topics[topic];
  const storyData = storyElements[topic];
  const scenarioIndex =
    (articleNumber + Math.floor(articleNumber / Object.keys(topics).length) * 2) %
    topicData.scenarioNames.length;

  return {
    scenarioIndex,
    actor: topicActors[topic][scenarioIndex % topicActors[topic].length],
    subject: topicData.scenarioNames[scenarioIndex],
    detail: topicData.observations[scenarioIndex],
    challenge: storyData.challenges[scenarioIndex],
    method: storyData.methods[scenarioIndex],
    outcome: storyData.outcomes[scenarioIndex],
    lesson: storyData.lessons[scenarioIndex],
    action: topicData.actions[scenarioIndex % topicData.actions.length],
    variant: Math.floor(articleNumber / 56),
  };
}

