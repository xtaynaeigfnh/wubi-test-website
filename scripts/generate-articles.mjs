function buildChat(articleNumber) {
  const index = (articleNumber - 1) % chatArticles.length;
  return `${chatArticles[index].text.trim()}\n\n${chatFollowUps[index]}`;
}

const articleSpecs = [
  { length: "short", count: 80, min: 80, preferred: 118 },
  { length: "medium", count: 70, min: 300, preferred: 410 },
  { length: "long", count: 30, min: 1000, preferred: 1220 },
];

const articles = [];
let serial = 1;
const topicNames = Object.keys(topics);

for (const spec of articleSpecs) {
  for (let i = 0; i < spec.count; i += 1) {
    const topic = topicNames[(serial + i) % topicNames.length];
    const story = buildStoryOutline(topic, serial);
    const titleBase = story.subject;
    const preferred = spec.preferred + ((i * 17) % Math.max(20, Math.floor(spec.preferred * 0.18)));
    const generated =
      spec.length === "short"
        ? buildShort(topic, serial)
        : buildRegular(topic, serial, spec.min, preferred);
    const contextualized = makeSentencesDistinct(generated, story);
    const text =
      spec.length === "short"
        ? clampAtSentence(contextualized, spec.min, 180)
        : clampAtSentence(
            contextualized,
            spec.min,
            spec.length === "medium" ? 600 : 1800,
          );
    articles.push({
      id: `${spec.length}-${String(i + 1).padStart(3, "0")}`,
      title: `${titleBase} · ${i + 1}`,
      length: spec.length,
      topic,
      wordCount: text.replace(/\s/g, "").length,
      version: 2,
      text,
    });
    serial += 1;
  }
}

for (let i = 0; i < 20; i += 1) {
  const text = buildChat(i + 1);
  articles.push({
    id: `water-${String(i + 1).padStart(3, "0")}`,
    title: chatArticles[i].title,
    length: "water",
    topic: "网络聊天",
    wordCount: text.replace(/\s/g, "").length,
    version: 2,
    text,
  });
}

const groups = {
  short: articles.filter((article) => article.length === "short"),
  medium: articles.filter((article) => article.length === "medium"),
  long: articles.filter((article) => article.length === "long"),
  water: articles.filter((article) => article.length === "water"),
};

await mkdir(outputDir, { recursive: true });
await writeFile(
  path.join(outputDir, "articles-index.json"),
  JSON.stringify(
    articles.map((article) => ({
      id: article.id,
      title: article.title,
      length: article.length,
      topic: article.topic,
      wordCount: article.wordCount,
      version: article.version,
    })),
    null,
    2,
  ),
);

for (const [name, rows] of Object.entries(groups)) {
  await writeFile(
    path.join(outputDir, `articles-${name}.json`),
    JSON.stringify(rows.map(({ id, text }) => ({ id, text }))),
  );
}

